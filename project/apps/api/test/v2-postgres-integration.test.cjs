const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { Client } = require('pg');
const { Test } = require('@nestjs/testing');
const { JwtService } = require('@nestjs/jwt');
const { PrismaService } = require('../dist/modules/persistence/prisma.service');
const { AdminUsersService } = require('../dist/modules/admin-users/admin-users.service');
const { AdminUsersController } = require('../dist/modules/admin-users/admin-users.controller');
const { BaseService } = require('../dist/modules/base-management/base.service');
const { BaseController } = require('../dist/modules/base-management/base.controller');
const { AuthenticationService } = require('../dist/modules/authentication/authentication.service');
const { JwtAuthGuard } = require('../dist/modules/authentication/jwt-auth.guard');
const { AdminAuthGuard } = require('../dist/modules/authentication/admin-auth.guard');
const { hashPassword } = require('../dist/modules/authentication/passwords');

const url = process.env.V2_TEST_DATABASE_URL;
const api = path.resolve(__dirname, '..');
const migrations = path.join(api, 'prisma', 'migrations');

test('populated migration and real database management integration', { skip: !url && 'Set V2_TEST_DATABASE_URL to a fresh disposable v2_disposable_test database', timeout: 120000 }, async () => {
  const parsed = new URL(url);
  assert.equal(parsed.pathname, '/v2_disposable_test', 'Use only an explicitly named disposable database');
  assert.ok(['127.0.0.1', 'localhost', '::1'].includes(parsed.hostname), 'Use only a local disposable database');
  process.env.DATABASE_URL = url;
  process.env.LOCAL_AUTH_ENABLED = 'true';
  process.env.ADMIN_USERNAMES = 'legacy-admin';
  process.env.AUTH_BOOTSTRAP_ENABLED = 'false';
  const scratch = fs.mkdtempSync(path.join(__dirname, '.v2-migration-'));
  const client = new Client({ connectionString: url });
  let prisma, app;
  try {
    await client.connect();
    const existing = await client.query("SELECT count(*)::int AS n FROM information_schema.tables WHERE table_schema = 'public'");
    assert.equal(existing.rows[0].n, 0, 'Database must be empty');
    fs.mkdirSync(path.join(scratch, 'migrations'));
    fs.copyFileSync(path.join(api, 'prisma', 'schema.prisma'), path.join(scratch, 'schema.prisma'));
    fs.writeFileSync(path.join(scratch, 'prisma.config.ts'), "import { defineConfig } from 'prisma/config';\nexport default defineConfig({ schema: './schema.prisma', migrations: { path: './migrations' }, datasource: { url: process.env.V2_TEST_DATABASE_URL! } });\n");
    const names = fs.readdirSync(migrations);
    const copy = (name) => fs.cpSync(path.join(migrations, name), path.join(scratch, 'migrations', name), { recursive: true });
    names.filter((n) => n === 'migration_lock.toml' || n < '20261112013000_account_session_revocation').forEach(copy);
    const deploy = () => execFileSync(process.execPath, [path.join(api, 'node_modules', 'prisma', 'build', 'index.js'), 'migrate', 'deploy', '--config', path.join(scratch, 'prisma.config.ts')], { cwd: api, env: process.env, stdio: 'pipe' });
    deploy();
    const userId = 'cedd8acb-32de-45b3-954b-31c7cbf8c923';
    const jobId = 'c6fc5688-d1a7-47e7-9a77-e55d95fd12a4';
    const secret = 'a long exact legacy password';
    const hash = await hashPassword(secret);
    await client.query('INSERT INTO "User" (id, username, email, gid, "passwordHash", "updatedAt") VALUES ($1,$2,$3,$4,$5,now())', [userId, 'legacy-admin', 'legacy@example.com', 'OLD-1', hash]);
    await client.query('INSERT INTO "UserIdentity" (id, provider, subject, "userId") VALUES ($1,$2,$3,$4)', ['9ef9af94-8425-4c0b-b003-577b203b877a', 'LOCAL', 'legacy-admin', userId]);
    await client.query('INSERT INTO "TranslationJob" (id, "ownerId", "fileName", "fileSize", "mimeType", "sourceLanguage", "targetLanguage", "selectedSheets", "sourcePath", "updatedAt") VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,now())', [jobId, userId, 'legacy.xlsx', 1, 'application/xlsx', 'JAPANESE', 'ENGLISH', '[]', '/legacy']);
    names.filter((n) => n !== 'migration_lock.toml' && n >= '20261112013000_account_session_revocation').forEach(copy);
    deploy();
    deploy();
    const legacy = await client.query('SELECT u.id, u.enabled, u."sessionVersion", u."baseId", i."userId", j."ownerId" FROM "User" u JOIN "UserIdentity" i ON i."userId"=u.id JOIN "TranslationJob" j ON j."ownerId"=u.id WHERE u.id=$1', [userId]);
    assert.deepEqual(legacy.rows[0], { id: userId, enabled: true, sessionVersion: 0, baseId: null, userId, ownerId: userId });
    const seeded = await client.query('SELECT code FROM "Base" ORDER BY code');
    assert.deepEqual(seeded.rows.map((row) => row.code), ['CGTY','JTY','KKTY','MSTY','PTY']);

    prisma = new PrismaService();
    const users = new AdminUsersService(prisma);
    const bases = new BaseService(prisma);
    const base = await prisma.base.findFirst({ where: { code: 'JTY' } });
    const register = (i) => users.create({ gid: `G-${i}`, username: `user-${i}`, email: i === 1 ? 'SAME@example.com' : 'same@example.com', baseId: base.id, password: 'a sufficiently long password' });
    const attempts = await Promise.allSettled([register(1), register(2)]);
    assert.equal(attempts.filter((a) => a.status === 'fulfilled').length, 1, 'Exactly one concurrent case-insensitive duplicate email registration succeeds');
    assert.equal(attempts.find((a) => a.status === 'rejected').reason.status, 409);
    assert.equal(await prisma.user.count({ where: { email: { equals: 'same@example.com', mode: 'insensitive' } } }), 1);
    const created = attempts.find((a) => a.status === 'fulfilled').value;
    assert.equal(await prisma.userIdentity.count({ where: { userId: created.id, provider: 'LOCAL' } }), 1);
    await assert.rejects(users.create({ gid: 'G-invalid', username: 'invalid-base', email: 'invalid-base@example.com', baseId: 'ffffffff-ffff-ffff-ffff-ffffffffffff', password: 'a sufficiently long password' }), (error) => error.status === 400);
    assert.equal(await prisma.user.count({ where: { username: 'invalid-base' } }), 0);
    await assert.rejects(bases.remove(base.id), (error) => error.status === 409);
    const filtered = await users.list({ q: 'JTY', baseId: base.id, enabled: 'true', sort: 'username', direction: 'asc', page: '1', pageSize: '10' });
    assert.equal(filtered.total, 1);
    assert.equal(filtered.data[0].id, created.id);

    const jwt = new JwtService({ secret: 'disposable-integration-only', signOptions: { expiresIn: '10m' } });
    const auth = new AuthenticationService(jwt, prisma, { verify: async () => { throw new Error('OIDC unavailable in this test'); } });
    const admin = await auth.validateUser('legacy-admin', secret);
    assert.equal(admin.isAdmin, true);
    const adminToken = (await auth.login(admin)).access_token;
    const normal = await auth.validateUser(created.username, 'a sufficiently long password');
    const userToken = (await auth.login(normal)).access_token;
    const moduleRef = await Test.createTestingModule({ controllers: [AdminUsersController, BaseController], providers: [JwtAuthGuard, AdminAuthGuard, { provide: AuthenticationService, useValue: auth }, { provide: AdminUsersService, useValue: users }, { provide: BaseService, useValue: bases }] }).compile();
    app = moduleRef.createNestApplication(); await app.listen(0);
    const baseUrl = `http://127.0.0.1:${app.getHttpServer().address().port}`;
    const request = (route, token, options = {}) => fetch(`${baseUrl}${route}`, { ...options, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...options.headers } });
    assert.equal((await request('/admin/users')).status, 401);
    assert.equal((await request('/admin/users', userToken)).status, 403);
    assert.equal((await request('/admin/bases', userToken)).status, 403);
    assert.equal((await request('/admin/users', adminToken)).status, 200);
    const nextBase = await prisma.base.findFirst({ where: { code: 'KKTY' } });
    const patchBase = (token, baseId) => request(`/admin/users/${created.id}/base`, token, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ baseId }) });
    assert.equal((await patchBase(userToken, nextBase.id)).status, 403);
    assert.equal((await patchBase(adminToken, 'ffffffff-ffff-ffff-ffff-ffffffffffff')).status, 400);
    assert.equal((await prisma.user.findUnique({ where: { id: created.id } })).baseId, base.id);
    assert.equal((await patchBase(adminToken, nextBase.id)).status, 200);
    assert.equal((await prisma.user.findUnique({ where: { id: created.id } })).baseId, nextBase.id);
    await assert.rejects(bases.remove(nextBase.id), (error) => error.status === 409);
    await prisma.user.update({ where: { id: userId }, data: { enabled: false } });
    assert.equal((await request('/admin/users', adminToken)).status, 401, 'Disablement revokes an already-issued token');
    assert.equal(await auth.validateUser('legacy-admin', secret), null);
  } finally {
    if (app) await app.close();
    if (prisma) await prisma.$disconnect();
    await client.end();
    fs.rmSync(scratch, { recursive: true, force: true });
  }
});
